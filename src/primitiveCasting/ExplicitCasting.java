package primitiveCasting;

public class ExplicitCasting {
	
	public static void main(String[] args) {
		
		int i=100000;
		short a=(short)i;
		System.out.println(a);
		
		float o=57.99f;
		short m=(short)o;
		System.out.println(m);
		
		double d=45454545;
		float g=(float)d;
		System.out.println(g);
		
	}

}
