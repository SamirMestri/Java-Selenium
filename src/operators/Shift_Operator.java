package operators;

public class Shift_Operator {

public static void main(String[] args) {
		
		// right shift operator (>>)
		// left shift operator  (<<)
		
		int a=10;
		System.out.println(a>>2); // 10/2^2 = 2
		System.out.println(a>>3); //10/2^3 =1
		
		//left shift operator 
		
		System.out.println(a<<2); //10*2^2 = 40
		System.out.println(a<<5); //10*2^5 = 320
	}

	
}
