package operators;

public class ArithmeticOperator {

		public static void main(String[] args) {
			// addition
			int a = 10;
			int b = 20;
			int c = a + b;
			System.out.println(c);

			// substraction
			int a1 = 30;
			int b1 = 20;
			int c1 = a1 - b1;
			System.out.println(c1);

			// multiplication
			int a2 = 30;
			int b2 = 20;
			int c2 = a2 * b2;
			System.out.println(c2);

			// division
			int d = 20;
			int e = 10;
			int f = d / e;
			System.out.println(f); // answer -->Quotient

			// percentage symbol
			int g = 25;
			int h = 10;
			int i = g % h;
			System.out.println(i); // answer -->Remainder

		}

	}	
	
	
	

