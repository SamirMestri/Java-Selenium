package logicalPrograming;

public class Swap2Numbers {
	
	public static void main(String[] args) {
		
		
		//using 3 variables
		
		int a=10;
		int b=20;
		int c;
		System.out.println("before swaping "+a+"<-->"+b);
		
		c=b;
		b=a;
		a=c;
		
		System.out.println("After Swaping number"+a+"<-->"+b);
		
	}
	

}
